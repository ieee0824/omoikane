pub(super) fn is_quirks(token: &DoctypeToken) -> bool {
    let public = token.public_id().unwrap_or_default().to_ascii_lowercase();
    let system = token.system_id().unwrap_or_default();
    token.force_quirks()
        || token.name() != Some("html")
        || matches!(
            public.as_str(),
            "-//w3o//dtd w3 html strict 3.0//en//" | "-/w3c/dtd html 4.0 transitional/en" | "html"
        )
        || system.eq_ignore_ascii_case("http://www.ibm.com/data/dtd/v11/ibmxhtml1-transitional.dtd")
        || PUBLIC_PREFIXES
            .iter()
            .any(|prefix| public.starts_with(prefix))
        || (system.is_empty()
            && [
                "-//w3c//dtd html 4.01 frameset//",
                "-//w3c//dtd html 4.01 transitional//",
            ]
            .iter()
            .any(|prefix| public.starts_with(prefix)))
}
